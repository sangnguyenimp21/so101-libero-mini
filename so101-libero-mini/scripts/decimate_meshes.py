"""One-time asset step: decimated copies of the SO-101 *visual* meshes for fast CPU (OSMesa) rendering.

The Menagerie meshes have 17k-54k faces each (348k in total), which makes llvmpipe rendering ~250 ms per
256x256 frame. Collision geometry is not touched (the gripper collision meshes and primitives are used as is),
so physics is identical with either set; only the look changes slightly.

    bash scripts/env.sh python scripts/decimate_meshes.py    # needs: pip install --target $SCRATCH/opt/meshtools
                                                              #        fast-simplification==0.1.11 trimesh==4.8.3
"""

from __future__ import annotations

import os
import sys
from pathlib import Path

sys.path.insert(0, os.environ.get("MESHTOOLS", "/scratch/e1583535/opt/meshtools"))

import fast_simplification  # noqa: E402
import mujoco  # noqa: E402
import numpy as np  # noqa: E402
import trimesh  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "assets" / "robotstudio_so101"
DST = ROOT / "assets" / "robotstudio_so101_lowpoly"
TARGET_FRACTION = 0.08
MIN_FACES = 1500


def visual_meshes(spec: mujoco.MjSpec) -> set[str]:
    names = set()
    for g in spec.geoms:
        if g.type == mujoco.mjtGeom.mjGEOM_MESH and g.contype == 0 and g.conaffinity == 0:
            names.add(g.meshname)
    return names


def main() -> None:
    spec = mujoco.MjSpec.from_file(str(SRC / "so101.xml"))
    DST.mkdir(exist_ok=True)
    rows = []
    for mesh in spec.meshes:
        if (mesh.name or Path(mesh.file).stem) not in visual_meshes(spec):  # unnamed meshes take the file stem
            continue
        src = SRC / "assets" / mesh.file
        tm = trimesh.load(src, process=True)  # merges duplicate STL vertices
        n = len(tm.faces)
        target = max(MIN_FACES, int(n * TARGET_FRACTION))
        if n > target:
            v, f = fast_simplification.simplify(np.asarray(tm.vertices, np.float32), np.asarray(tm.faces), 1 - target / n)
            tm = trimesh.Trimesh(v, f, process=True)
        tm.export(DST / mesh.file)
        rows.append(f"| {mesh.file} | {n} | {len(tm.faces)} |")
        print(f"{mesh.file}: {n} -> {len(tm.faces)} faces")
    (DST / "README.md").write_text(
        "# Decimated SO-101 visual meshes\n\nGenerated by `scripts/decimate_meshes.py` from `../robotstudio_so101/assets`"
        f" (quadric decimation to {TARGET_FRACTION:.0%} of the faces, at least {MIN_FACES}). Only visual geoms use them;"
        " collision geometry is unchanged. Apache-2.0, like the source meshes.\n\n| mesh | faces | decimated |\n|---|---|---|\n"
        + "\n".join(rows) + "\n")


if __name__ == "__main__":
    main()
